#ifndef __COMM_H
#define __COMM_H

#include "main.h"

/*********************************************************************
 * 串口命令解析（BSP 层，放在 USART2 之上）
 *
 *   协议：上位机发送 ASCII 十进制角度 + 回车/换行
 *         例如 "120\r\n"、"90\n"
 *   有效条件：整帧全部是数字，且数值在 0 ~ 180 之间
 *   无效帧（含非数字字符、超范围、超长）直接丢弃，
 *   不会改变舵机角度，也不会让蜂鸣器响。
 *
 *   有效帧通过 Comm_PopTarget() 取走（取走即清除标志），
 *   主循环里处理，避免在中断里做 OLED/舵机这些耗时操作。
 *********************************************************************/

void    Comm_Init(void);                  /* 打开 USART2 接收中断 */
uint8_t Comm_PopTarget(int32_t *Angle);   /* 1 = 取到了新的有效目标角度 */

#endif
